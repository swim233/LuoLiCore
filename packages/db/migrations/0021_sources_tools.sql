-- 按来源可配的 SDK 工具白名单（docs/12-sdk.md §8）。
--
-- 此前 SDK 档的工具集是编译期常量 SDK_AGENT_TOOLS，三件记忆工具，全部来源共用一份。那是
-- 批三「本次不做工具调用」的范围决定（docs/12 §1），不是安全结论——角色轴（恒 trusted）才是
-- 安全边界，agentKind 轴回答的是「这一档 agent 该拿哪些」。接入方之间的需求差异落在来源这
-- 一维：同一个实例上，一个只要对话的客户端和一个要读写文件的客户端不该被同一份常量绑在一起。
--
-- 落 sources 而不落 api_keys：密钥签发时绑定来源（docs/12 §3.1），同一来源可以有多把密钥，
-- 轮换密钥不应连带改变这个来源能做什么。按密钥配会让「换一把钥匙」变成一次权限变更。
--
-- NULL 表示「用默认」，不是「一件都不给」。存量行全部为 NULL，判据在读侧回落到
-- SDK_AGENT_TOOLS——因此这次迁移不改变任何现有部署的行为，也不需要回填。
-- 空数组 '[]' 与 NULL 不同：它是显式的「这个来源一件工具都不给」，是可配置的一种取值。
