-- log_events 搬进了 logs.dbPath 那个独立文件（docs/10 §3）。主库这张同名表必须消失：
-- SQLite 按 temp → main → attached 解析表名，它只要还在就会一直遮住附加库那张，于是所有
-- 查询读到的都是一张永远不再增长的旧表 —— 而没有任何断言会因此变红，日志页只是静静地空着。
--
-- 存量行的搬迁由 `importLegacyLogEvents` 完成，它跑在「已 ATTACH」与「本次迁移」之间，
-- 且自己就带着同一句 DROP。所以这条迁移在**升级**那一路是兜底，在**空库**那一路才是唯一的
-- 删除点（0001 照旧会先把这张表建出来 —— 迁移文件一旦提交就不可修改，只能追加）。
-- 索引随表一起消失，不必单独 DROP；写 main. 前缀是为了不会在重跑时误伤附加库里的同名索引。
DROP TABLE IF EXISTS main.log_events;
