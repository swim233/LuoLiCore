/* 「面板上会变的地方」：换成库的组件以后，面板上每一处会变的样子（完全不变的不列）。
   这张表是请用户点头的清单：4b 换完以后，面板上除了这里列的，不能有别的变化。
   每一行的数字都由 QA 的脚本对着对比块量出来的计算样式核对过：对比块里「现在」和「归并后」两边，
   每个被量的元素（data-item、data-state）差了哪些属性，都必须出现在某一行的 targets 和 props 里，没有漏列。 */
export interface Change {
  id: string;
  /** 哪个部件 */
  part: string;
  /** 哪个东西（旧类名） */
  where: string;
  /** 变的是什么 */
  what: string;
  now: string;
  after: string;
  diff: string;
  /** 对应哪些被量的元素，写成「data-item:data-state」 */
  targets: string[];
  /** 对应哪些量出来的属性（核对用）：padding*、fontSize、h（高）、w（宽）、radius（四个角）、backgroundColor、hover.xxx…… */
  props: string[];
  /** 只有一个数字时，脚本核对 props[0] 量出来的就是这两个值（px 或不透明度） */
  nowNum?: number;
  afterNum?: number;
}

